"""Generate size-parametrised variants of the corpus programs.

The originals in ``tests/jana2014/fixtures/examples/`` are never modified
(rc03.tex:205: 入力は縮小版と拡大版を別に用意し，コーパスの原本は改変していない).
For each variant the procedures of the original are copied verbatim and only
the ``main`` procedure (declarations + input initialisation) is rewritten.

Families (see README.md):

* ``gcd_fib``   gcd.ja with consecutive Fibonacci arguments a=F(k+2), b=F(k+1),
                k = 1..20.  Predicted stack_peak = k (one log bit per
                subtraction; consecutive Fibonacci numbers make every Euclid
                quotient 1, so k subtractions).
* ``gcd_pair``  gcd.ja with a few non-Fibonacci pairs.  Predicted
                stack_peak = (sum of the Euclid quotients) - 1.
* ``bubble_sort``      bubble_sort.ja, n = 2..21, reverse-sorted input
                       (call bsort(a) ... uncall bsort(ord), like the original).
* ``bubble_sort_fwd``  the same but only the forward ``call bsort(a,sz,gb)``
                       (no ord/uncall half); this is the shape whose steps
                       reproduce rc03's scaling row exactly.
* ``bubble_sort_perm`` bubble_sort.ja, a deterministic pseudo-random
                       permutation, a few n.  Predicted stack_peak =
                       n(n-1)/2 in both cases (one garbage bit per
                       comparison, independent of the input order).
* ``knapsack``  knapsack.ja with n items, cap = n+2 (the original is n=3,
                cap=5), wt[i]=i+1, val[i]=i+2.  Predicted stack_peak = 0.
* ``lcs``       lcs.ja with m = n = s over a 4-letter alphabet.  Predicted 0.
* ``edit_distance`` edit_distance.ja with m = n = s.  Predicted 0.

Run ``python3 -m tests.resource_atlas.gen_inputs`` to (re)write
``tests/resource_atlas/generated/``.
"""
from __future__ import annotations

import random
from dataclasses import dataclass
from pathlib import Path

from .common import GENERATED_DIR, ROOT

EXAMPLES = ROOT / "tests" / "jana2014" / "fixtures" / "examples"
STD = "jana2014"


@dataclass(frozen=True)
class Variant:
    family: str
    size: int
    param: str                    # human-readable parameter, e.g. "a=F(7)=13,b=F(6)=8"
    filename: str
    predicted_stack_peak: int
    original: str                 # fixture the procedures are copied from

    @property
    def path(self) -> Path:
        return GENERATED_DIR / self.filename


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _procedures_of(fixture: str) -> str:
    """Everything of the fixture before `procedure main()` (header + procs)."""
    text = (EXAMPLES / fixture).read_text()
    idx = text.index("procedure main()")
    return text[:idx]


def _header(v: Variant) -> str:
    return (
        "// ---- GENERATED by tests/resource_atlas/gen_inputs.py -- do not edit ----\n"
        f"// family={v.family} size={v.size} {v.param}\n"
        f"// procedures copied verbatim from {v.original}; only main() differs.\n"
        f"// predicted stack_peak = {v.predicted_stack_peak}\n\n"
    )


def fib(n: int) -> int:
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a


def euclid_quotient_sum(a: int, b: int) -> int:
    total = 0
    while b:
        total += a // b
        a, b = b, a % b
    return total


# ---------------------------------------------------------------------------
# main() renderers
# ---------------------------------------------------------------------------

def _gcd_main(a: int, b: int) -> str:
    return (
        "procedure main()\n"
        "  int a\n"
        "  int b\n"
        "  stack log\n"
        "\n"
        f"  a += {a}\n"
        f"  b += {b}\n"
        "  call gcd(a,b,log)\n"
    )


def _bubble_main(values: list[int], forward_only: bool = False) -> str:
    n = len(values)
    if forward_only:
        lines = [
            "procedure main()",
            f"  int a[{n}]     // input array",
            "  int sz       // size of stk[]",
            "  stack gb     // garbage stack",
            "",
            f"  sz += {n}",
        ]
        lines += [f"  a[{i}] += {val}" for i, val in enumerate(values)]
        lines += ["", "  call bsort(a,sz,gb)", ""]
        return "\n".join(lines)
    lines = [
        "procedure main()",
        f"  int a[{n}]     // input array",
        "  int sz       // size of stk[]",
        "  stack gb     // garbage stack",
        f"  int ord[{n}]   // permutation",
        "",
        f"  sz += {n}",
    ]
    lines += [f"  a[{i}] += {val}" for i, val in enumerate(values)]
    lines += ["", "  call bsort(a,sz,gb)", ""]
    lines += [f"  ord[{i}] += {i}" for i in range(n)]
    lines += ["", "  uncall bsort(ord,sz,gb)", ""]
    return "\n".join(lines)


def _knapsack_main(n: int) -> str:
    cap = n + 2
    lines = [
        "procedure main()",
        f"  int wt[{n + 1}]    // weights,  1-indexed",
        f"  int val[{n + 1}]   // values,   1-indexed",
        "  int n",
        "  int cap",
        f"  int K[{(n + 1) * (cap + 1)}]    // (n+1) x (cap+1) = {n + 1} x {cap + 1}",
        "",
        f"  n += {n}",
        f"  cap += {cap}",
    ]
    lines += [f"  wt[{i}] += {i + 1}  val[{i}] += {i + 2}" for i in range(1, n + 1)]
    lines += ["", "  call knapsack(wt,val,n,cap,K)", ""]
    return "\n".join(lines)


def _seq_x(s: int) -> list[int]:
    return [((i * 7) % 4) + 1 for i in range(1, s + 1)]


def _seq_y(s: int) -> list[int]:
    return [((j * 5 + 1) % 4) + 1 for j in range(1, s + 1)]


def _lcs_main(s: int) -> str:
    x, y = _seq_x(s), _seq_y(s)
    lines = [
        "procedure main()",
        f"  int x[{s + 1}]     // x[0] unused",
        f"  int y[{s + 1}]     // y[0] unused",
        "  int m",
        "  int n",
        f"  int L[{(s + 1) * (s + 1)}]    // (m+1) x (n+1) = {s + 1} x {s + 1}",
        "",
        f"  m += {s}",
        f"  n += {s}",
        "  " + " ".join(f"x[{i + 1}]+={v}" for i, v in enumerate(x)),
        "  " + " ".join(f"y[{j + 1}]+={v}" for j, v in enumerate(y)),
        "",
        "  call lcs(x,m,y,n,L)",
        "",
    ]
    return "\n".join(lines)


def _edit_main(s: int) -> str:
    x, y = _seq_x(s), _seq_y(s)
    lines = [
        "procedure main()",
        f"  int x[{s + 1}]     // x[0] unused",
        f"  int y[{s + 1}]     // y[0] unused",
        "  int m",
        "  int n",
        f"  int D[{(s + 1) * (s + 1)}]    // (m+1) x (n+1) = {s + 1} x {s + 1}",
        "",
        f"  m += {s}",
        f"  n += {s}",
        "  " + " ".join(f"x[{i + 1}]+={v}" for i, v in enumerate(x)),
        "  " + " ".join(f"y[{j + 1}]+={v}" for j, v in enumerate(y)),
        "",
        "  call edit_distance(x,m,y,n,D)",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# variant catalogue
# ---------------------------------------------------------------------------

GCD_PAIRS = [(48, 36), (100, 7), (60, 25), (17, 5), (99, 1), (1000, 3)]
PERM_SIZES = [5, 8, 13, 21]
DP_SIZES = range(1, 21)


def variants() -> list[Variant]:
    out: list[Variant] = []
    for k in range(1, 21):
        a, b = fib(k + 2), fib(k + 1)
        out.append(Variant("gcd_fib", k, f"a=F({k + 2})={a} b=F({k + 1})={b}",
                           f"gcd_fib_k{k:02d}.ja", k, "gcd.ja"))
    for a, b in GCD_PAIRS:
        q = euclid_quotient_sum(a, b)
        out.append(Variant("gcd_pair", q - 1, f"a={a} b={b} sum_of_quotients={q}",
                           f"gcd_pair_{a}_{b}.ja", q - 1, "gcd.ja"))
    for n in range(2, 22):
        out.append(Variant("bubble_sort", n, f"n={n} reverse-sorted",
                           f"bubble_sort_n{n:02d}.ja", n * (n - 1) // 2, "bubble_sort.ja"))
    for n in range(2, 22):
        out.append(Variant("bubble_sort_fwd", n, f"n={n} reverse-sorted, call only",
                           f"bubble_sort_fwd_n{n:02d}.ja", n * (n - 1) // 2, "bubble_sort.ja"))
    for n in PERM_SIZES:
        out.append(Variant("bubble_sort_perm", n, f"n={n} pseudo-random permutation (seed {n})",
                           f"bubble_sort_perm_n{n:02d}.ja", n * (n - 1) // 2, "bubble_sort.ja"))
    for n in DP_SIZES:
        out.append(Variant("knapsack", n, f"n={n} cap={n + 2}", f"knapsack_n{n:02d}.ja", 0, "knapsack.ja"))
    for s in DP_SIZES:
        out.append(Variant("lcs", s, f"m=n={s}", f"lcs_n{s:02d}.ja", 0, "lcs.ja"))
    for s in DP_SIZES:
        out.append(Variant("edit_distance", s, f"m=n={s}", f"edit_distance_n{s:02d}.ja", 0, "edit_distance.ja"))
    return out


def render(v: Variant) -> str:
    procs = _procedures_of(v.original)
    if v.family == "gcd_fib":
        k = v.size
        main = _gcd_main(fib(k + 2), fib(k + 1))
    elif v.family == "gcd_pair":
        a, b = (int(t.split("=")[1]) for t in v.param.split()[:2])
        main = _gcd_main(a, b)
    elif v.family == "bubble_sort":
        main = _bubble_main([(v.size - i) * 10 for i in range(v.size)])
    elif v.family == "bubble_sort_fwd":
        main = _bubble_main([(v.size - i) * 10 for i in range(v.size)], forward_only=True)
    elif v.family == "bubble_sort_perm":
        perm = list(range(v.size))
        random.Random(v.size).shuffle(perm)
        main = _bubble_main([(p + 1) * 10 for p in perm])
    elif v.family == "knapsack":
        main = _knapsack_main(v.size)
    elif v.family == "lcs":
        main = _lcs_main(v.size)
    elif v.family == "edit_distance":
        main = _edit_main(v.size)
    else:  # pragma: no cover
        raise ValueError(v.family)
    return _header(v) + procs + main


def write_all(directory: Path = GENERATED_DIR) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for v in variants():
        path = directory / v.filename
        path.write_text(render(v))
        written.append(path)
    return written


if __name__ == "__main__":
    paths = write_all()
    print(f"wrote {len(paths)} variants to {GENERATED_DIR}")
